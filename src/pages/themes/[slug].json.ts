import type { APIRoute } from "astro";
import themesIndex from "../../data/themes-index.json";
import themesFull from "../../data/themes-full.json";
import { buildThemeJson } from "../../lib/themeBuilder/serialize.mjs";

// Import-ready `theme.json` for one gallery theme, served from THIS origin.
//
// Why the site serves the palette itself: the themes index used to point every
// card's download at `raw.githubusercontent.com/myne-md/myne-themes/...`, which
// 404s for anyone not signed in to the org: the repository is private, and a
// raw URL carries no credentials. Every "Download .json" on /themes was a dead
// link in production while the page and the previews worked, so nothing around
// it looked broken.
//
// The palette is already in this repo (`themes-full.json`, vendored for the
// builder's "start from a gallery theme" preset), and `buildThemeJson` is the
// same projection the builder exports: canonical tokens only, blanks dropped,
// key-sorted. So the file a reader downloads is byte-for-byte what the builder
// would have handed them, produced at build time with no fetch, no tracker and
// no runtime dependency on the themes repository.
export const prerender = true;

const palettes = themesFull as Record<string, Record<string, string>>;

export function getStaticPaths() {
  return (themesIndex.themes ?? []).map((t) => {
    // FAIL THE BUILD, do not filter. The card renders a download link for every
    // entry in the index, so a theme whose palette has not landed yet would ship
    // a live-looking link to a 404: which is the exact failure this route
    // exists to close (`themes-index.json` is generated by `myne-themes` CI and
    // `themes-full.json` by `sync-themes.mjs`, so the two can arrive out of
    // step). A build that stops here is the honest half of that pair.
    if (!palettes[t.slug]) {
      throw new Error(
        `themes/${t.slug}.json: the index lists "${t.name}" but themes-full.json has no palette for it. ` +
          `Run \`pnpm sync-themes\`, or drop the entry from the index.`,
      );
    }
    return { params: { slug: t.slug } };
  });
}

export const GET: APIRoute = ({ params }) => {
  const palette = palettes[params.slug ?? ""];
  if (!palette) return new Response("Not found", { status: 404 });
  return new Response(JSON.stringify(buildThemeJson(palette), null, 2) + "\n", {
    headers: {
      "content-type": "application/json; charset=utf-8",
      // A theme palette is a build artefact of this deploy: a new build is a new
      // URL-identical body, so revalidate rather than cache hard. (Fingerprinted
      // `/_astro/` assets are the ones that get `immutable`.)
      "cache-control": "public, max-age=300",
    },
  });
};
